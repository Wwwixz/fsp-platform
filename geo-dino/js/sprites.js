/* Гео-Динозавр — пиксель-арт спрайты.
   Каждый спрайт задан картой символов: '#' — тело, 'o' — «прозрачный»
   глаз (цвет фона), '@' — акцент. Отрисовка — целыми пикселями, без сглаживания. */
(function (ns) {
  'use strict';

  var COLORS = {
    ink: '#2a2d33',    // динозавр и кактусы
    eye: '#ececec',    // глаз = цвет фона поля
    cloud: '#d6d6dc',
    ground: '#8f959c',
    mountFar: '#e0e0e6',
    mountNear: '#d2d2da',
    dust: '#b9bcc2'
  };

  /* Тело динозавра 22×15 (без ног) — смотрит вправо */
  var DINO_BODY = [
    '..............#######.',
    '.............#####o###',
    '.............#########',
    '.............#########',
    '.............######...',
    '.............#######..',
    '.............####.....',
    '.............#####....',
    '#...........######....',
    '##..........########..',
    '###.........#######...',
    '####........#######...',
    '#####.......#######...',
    '######......######....',
    '.#######....######....'
  ];

  /* Ноги 22×5 — кадры бега/стояния/прыжка */
  var LEGS = {
    stand: [
      '..##############......',
      '....####..#####.......',
      '....####...####.......',
      '....####...####.......',
      '...#####...#####......'
    ],
    runA: [
      '..##############......',
      '....####..#####.......',
      '....##....####........',
      '....###...####........',
      '..........#####.......'
    ],
    runB: [
      '..##############......',
      '....####..#####.......',
      '....####...###........',
      '....####....##........',
      '...#####..............'
    ],
    jump: [
      '..##############......',
      '....####..#####.......',
      '....###....###........',
      '....##.....##.........',
      '......................'
    ]
  };

  /* «Крестик» глаз вместо точки — для погибшего динозавра, [колонка, строка] */
  var DEAD_EYE = [[17, 0], [19, 0], [17, 2], [19, 2]];

  /* Кактусы */
  var CACTUS_SMALL = [ // 10×20
    '...####...',
    '...####...',
    '...####...',
    '#..####..#',
    '#..####..#',
    '#..####..#',
    '#..####..#',
    '#..####..#',
    '#######...',
    '#######...',
    '...#######',
    '...#######',
    '...####...',
    '...####...',
    '...####...',
    '...####...',
    '...####...',
    '...####...',
    '...####...',
    '...####...'
  ];

  var CACTUS_BIG = [ // 12×28
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '#...####...#',
    '#...####...#',
    '#...####...#',
    '#...####...#',
    '#...####...#',
    '#...####...#',
    '#########...',
    '#########...',
    '....########',
    '....########',
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '....####....',
    '....####....'
  ];

  /* Облако 16×4 */
  var CLOUD = [
    '.....######.....',
    '...##########...',
    '.##############.',
    '################'
  ];

  /* Рисует карту символов: каждый '#' — квадрат px×px в точке (x, y) */
  function drawMap(ctx, rows, x, y, px, color, eyeColor) {
    ctx.fillStyle = color;
    var r, c, row;
    var x0 = Math.round(x), y0 = Math.round(y);
    for (r = 0; r < rows.length; r++) {
      row = rows[r];
      for (c = 0; c < row.length; c++) {
        var ch = row.charAt(c);
        if (ch !== '#') continue;
        // глаз рисуем цветом фона, чтобы «дырка» читалась на теле
        ctx.fillStyle = (ch === '#') ? color : eyeColor;
        ctx.fillRect(x0 + c * px, y0 + r * px, px, px);
      }
    }
  }

  /* Динозавр целиком: тело + кадр ног + мёртвые глаза при dead */
  function drawDino(ctx, x, y, px, frame, dead) {
    drawMap(ctx, DINO_BODY, x, y, px, COLORS.ink);
    drawMap(ctx, LEGS[frame] || LEGS.stand, x, y + DINO_BODY.length * px, px, COLORS.ink);
    // глаз-точка уже «пробит» символом o в карте; перекрашиваем прозрачный px не нужно.
    if (dead) {
      // рисуем крестик поверх глаза (два пикселя сверху/снизу + боковые)
      ctx.fillStyle = COLORS.eye;
      for (var i = 0; i < DEAD_EYE.length; i++) {
        ctx.fillRect(Math.round(x) + DEAD_EYE[i][0] * px, Math.round(y) + DEAD_EYE[i][1] * px, px, px);
      }
    }
  }

  ns.Sprites = {
    COLORS: COLORS,
    DINO_BODY: DINO_BODY,
    LEGS: LEGS,
    CACTUS_SMALL: CACTUS_SMALL,
    CACTUS_BIG: CACTUS_BIG,
    CLOUD: CLOUD,
    DINO_COLS: 22,
    DINO_ROWS: DINO_BODY.length + 5, // тело + ноги
    drawMap: drawMap,
    drawDino: drawDino
  };
})(window.GeoDino = window.GeoDino || {});
